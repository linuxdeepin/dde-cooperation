// Streaming compression codecs for the DTP2 archive stream.
//
// Threading: every StreamEncoder/StreamDecoder instance is owned by exactly one
// thread (the producer thread on the sending side, the consumer thread on the
// receiving side). Instances are not thread-safe and must never be shared.
//
// The classes are transport agnostic: they never touch sockets or files. Input
// is fed in arbitrary sized chunks and decoded output is appended to the
// caller supplied std::string.

#ifndef STREAMCODEC_H
#define STREAMCODEC_H

#include <cstddef>
#include <cstdint>
#include <memory>
#include <string>

namespace dtp {

// Wire codec identifiers. The numeric values are part of the protocol (DTP2
// preamble and the X-DTP-Codec header); never renumber them.
enum class Codec : uint8_t {
    None = 0,     // no compression, used for benchmarks / incompressible data
    Deflate = 1,  // zlib wrapper, permanent protocol baseline
    Zstd = 2,     // preferred codec for new peers
};

// Canonical wire name ("none", "deflate", "zstd"), or "" for invalid values.
const char *codecName(Codec codec);

// Parses a canonical wire name. Comparison is case sensitive on purpose: the
// name travels through the token claim and the request query, both generated by
// our own code.
bool codecFromName(const std::string &name, Codec *out);

// False when the codec is known but not compiled into this build (a build
// without HTTPWEB_HAVE_ZSTD). Codec::None is always available.
bool codecSupported(Codec codec);

// Default level: deflate 6, zstd 3 (protocol convention: zstd stays in 1..3).
int defaultCompressionLevel(Codec codec);

// Clamps a user supplied level into the valid range of the codec. Levels below
// 1 select the default.
int clampCompressionLevel(Codec codec, int level);

// Incremental encoder producing one compressed byte stream.
class StreamEncoder
{
public:
    StreamEncoder();
    ~StreamEncoder();

    StreamEncoder(const StreamEncoder &) = delete;
    StreamEncoder &operator=(const StreamEncoder &) = delete;

    // (Re)initialises the encoder. level < 0 selects defaultCompressionLevel().
    // Returns false when the codec is unknown or unavailable in this build.
    bool init(Codec codec, int level = -1);

    // Compresses data, appending whatever output is currently available to out.
    bool encode(const char *data, size_t size, std::string *out);

    // Flushes all buffered input so the decoder can emit everything fed so far.
    // The stream stays open; the producer calls this at file boundaries so the
    // receiver can finish a file without waiting for the whole archive.
    bool flush(std::string *out);

    // Terminates the compressed stream. Must be the last call. The output buffer
    // remains valid and may be appended to by the caller.
    bool finish(std::string *out);

    void reset();

    bool valid() const;
    Codec codec() const;
    const std::string &lastError() const;

private:
    struct Impl;
    std::unique_ptr<Impl> d;
};

// Incremental decoder consuming one compressed byte stream.
class StreamDecoder
{
public:
    StreamDecoder();
    ~StreamDecoder();

    StreamDecoder(const StreamDecoder &) = delete;
    StreamDecoder &operator=(const StreamDecoder &) = delete;

    // maxOutputBytes == 0 means "no limit". A non zero value protects against
    // decompression bombs; exceeding it is reported as an error.
    bool init(Codec codec, size_t maxOutputBytes = 0);

    // Decompresses data, appending the decoded bytes to out.
    bool decode(const char *data, size_t size, std::string *out);

    // True once the decoder consumed a complete compressed stream (deflate end
    // of stream marker / a complete zstd frame). Codec::None has no end marker,
    // so it never reports finished: there the archive END frame terminates the
    // transfer.
    bool finished() const;

    // Total number of decoded bytes since init().
    uint64_t totalOutput() const;

    void reset();

    bool valid() const;
    Codec codec() const;
    const std::string &lastError() const;

private:
    struct Impl;
    std::unique_ptr<Impl> d;
};

} // namespace dtp

#endif // STREAMCODEC_H
